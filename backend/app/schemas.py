    trace_id: str
    agent_name: str
    is_live_test: bool = False
    server_online: bool = True
    target_url: Optional[str] = None
    overall_security_score: float = 100.0
    safety_grade: str = "A+"
    threat_level: str = "SAFE"
    prompt_injection_status: str = "NONE"
    pii_leakage_status: str = "NO_LEAKAGE"
    system_prompt_leakage: str = "PROTECTED"
    role_boundary_status: str = "MAINTAINED"
    executive_summary: str = ""
    test_probes_executed: List[RedTeamProbe] = []
    vulnerabilities_found: List[str] = []
    remediation_guardrail: str = ""
    latency_ms: float = 0.0
    audited_by: str = "agentops-security-engine"
    heuristic_flags: Optional[Dict[str, Any]] = None


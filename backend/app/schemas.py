    metric: str = Field(..., description="hallucination_rate, error_rate, or cost_threshold")
    threshold: float = Field(..., description="Numeric trigger threshold")
    window_minutes: int = Field(60, ge=1, le=10080)
    target_email: EmailStr
    is_active: bool = True



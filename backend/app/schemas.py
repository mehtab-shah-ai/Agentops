from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, EmailStr, Field


# ------------------------------------------------------------------------------
# Auth & User Schemas
# ------------------------------------------------------------------------------
class UserRegisterRequest(BaseModel):
    email: EmailStr
    password: str = Field(..., min_length=8, description="User password (min 8 characters)")
    organization_name: Optional[str] = "Default Organization"


class UserLoginRequest(BaseModel):
    email: EmailStr
    password: str


class UserOut(BaseModel):
    id: str
    email: EmailStr
    organization_name: Optional[str]
    is_active: bool
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class TokenResponse(BaseModel):
    access_token: str
    token_type: str = "bearer"
    user: UserOut


class ApiKeyCreateRequest(BaseModel):
    name: str = Field("Default API Key", max_length=100)


class ApiKeyOut(BaseModel):
    id: str
    key_prefix: str
    name: str
    is_active: bool
    created_at: datetime
    last_used_at: Optional[datetime]

    model_config = ConfigDict(from_attributes=True)


class ApiKeyCreatedResponse(ApiKeyOut):
    api_key: str = Field(..., description="Plaintext API key - shown only once upon creation")


# ------------------------------------------------------------------------------
# Trace & Ingestion Schemas
# ------------------------------------------------------------------------------
class ToolCallRecord(BaseModel):
    tool_name: str
    arguments: Optional[Dict[str, Any]] = None
    output: Optional[Any] = None
    error: Optional[str] = None


class TraceIngestRequest(BaseModel):
    trace_id: str = Field(..., description="Root trace ID linking multi-step agent workflows")
    span_id: Optional[str] = Field(None, description="Unique span ID for this specific step/call")
    parent_span_id: Optional[str] = Field(None, description="Parent span ID for call tree reconstruction")
    agent_name: str = Field("default_agent", description="Name of the agent or pipeline component")
    task_type: str = Field("general", description="Classification of task, e.g. rag, code_gen, routing")
    model_name: str = Field("unknown", description="Model invoked, e.g. gpt-4o, llama-3.3-70b")

    input_query: str = Field(..., description="Original user prompt or input prompt to agent")
    context: Optional[str] = Field(None, description="Retrieved context, RAG passages, or reference data")
    output_result: str = Field(..., description="Raw output generated by the LLM/agent")

    latency_ms: float = Field(0.0, ge=0.0, description="Latency in milliseconds")
    input_tokens: int = Field(0, ge=0, description="Input/prompt token count")
    output_tokens: int = Field(0, ge=0, description="Completion/output token count")
    cost_usd: Optional[float] = Field(None, ge=0.0, description="Computed or tracked cost in USD")

    status: Optional[str] = Field("success", description="Status of the call: 'success' or 'failed'")
    failure_reasons: Optional[List[str]] = Field(default_factory=list, description="Explicitly logged failures")

    # Observability & deterministic rule verification metadata
    step_index: Optional[int] = Field(0, ge=0)
    max_steps_allowed: Optional[int] = Field(None, description="Configured step budget to verify step overrun")
    expected_schema: Optional[Dict[str, Any]] = Field(None, description="Expected JSON Schema for output validation")
    tool_calls: Optional[List[ToolCallRecord]] = Field(None, description="Sequence of tool calls for loop detection")
    metadata_json: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Arbitrary custom metadata")


class TraceIngestResponse(BaseModel):
    status: str
    trace_id: str
    span_id: str
    eval_status: str
    detected_failures: List[str] = []
    message: Optional[str] = None


class EvaluationOut(BaseModel):
    id: str
    trace_record_id: str
    hallucination_score: float
    faithfulness_score: float
    relevance_score: float
    claims_extracted: Optional[List[Any]] = []
    verdict: str
    eval_status: str
    judge_model: Optional[str] = None
    eval_latency_ms: Optional[float] = None
    reasoning: Optional[str] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class TraceDetailOut(BaseModel):
    id: str
    trace_id: str
    span_id: str
    parent_span_id: Optional[str]
    agent_name: str
    task_type: str
    model_name: str
    input_query: str
    context: Optional[str]
    output_result: str
    latency_ms: float
    input_tokens: int
    output_tokens: int
    cost_usd: float
    status: str
    failure_reasons: Optional[List[str]]
    step_index: Optional[int]
    metadata_json: Optional[Dict[str, Any]]
    created_at: datetime
    evaluation: Optional[EvaluationOut] = None

    model_config = ConfigDict(from_attributes=True)


class TraceTreeNode(BaseModel):
    span: TraceDetailOut
    children: List["TraceTreeNode"] = []


class TraceTreeResponse(BaseModel):
    trace_id: str
    root_spans: List[TraceTreeNode]
    total_spans: int
    total_latency_ms: float
    total_cost_usd: float
    has_failures: bool


